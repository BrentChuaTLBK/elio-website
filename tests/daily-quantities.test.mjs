import assert from 'node:assert/strict';
import {quantitySelection,quantitySaveRows,boxLimitSelection,boxLimitKey,boxLimitChanges} from '../dist/assets/admin/daily-quantities.js';
const product={id:'a',name:'Vanilla'}, dates=['2026-10-01','2026-10-02','2026-10-03'];
const rows=[{product_id:'a',date:dates[0],capacity:20,reserved:12,configured:true},{product_id:'a',date:dates[1],capacity:0,reserved:0,configured:true},{product_id:'a',date:dates[2],capacity:0,reserved:0,configured:false,available:false}];
assert.equal(quantitySelection('a',['2026-10-04'],rows).value,'0');
assert.equal(quantitySaveRows([product],rows,dates,{a:'25'},'2026-09-24','fill_unconfigured').length,1);
assert.equal(quantitySaveRows([product],rows,dates,{a:'25'},'2026-09-24','replace').length,3);
assert.throws(()=>quantitySaveRows([product],rows,dates,{a:'11'},'2026-09-24'),/12 already ordered/);
assert.equal(quantitySaveRows([product],rows,dates,{a:'11'},'2026-09-24','fill_unconfigured').length,1);
assert.equal(quantitySaveRows([product],[],['2026-10-04'],{a:'0'},'2026-09-24')[0].capacity,0);
const saved=[{date:dates[0],capacity:20,reserved:17,configured:true},{date:dates[1],capacity:null,reserved:2,configured:false}];
assert.equal(boxLimitSelection([dates[0]],saved).status,'3 left · 17 already booked');
assert.equal(boxLimitSelection(dates,saved).mixed,true);
assert.match(boxLimitSelection([dates[0]],saved,{[boxLimitKey]:'0'}).status,/0 left/);
assert.deepEqual(boxLimitChanges(dates,saved,{a:'20'}),[]);
assert.deepEqual(boxLimitChanges(dates,saved,{[boxLimitKey]:'0'},'fill_unconfigured').map(r=>r.date),dates.slice(1));
assert.deepEqual(boxLimitChanges([dates[0]],saved,{[boxLimitKey]:''}),[{date:dates[0],capacity:null,expected:20,configured:true}]);
assert.throws(()=>boxLimitChanges(dates,saved,{[boxLimitKey]:'2.5'}),/whole box limit/);
console.log('PASS flavor quantities, shared box limits, mixed dates and removal');
