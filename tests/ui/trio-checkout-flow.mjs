import assert from 'node:assert/strict';

export async function verifyTrio(ctx,h,origin,fixed,date) {
  const vanilla=await h.product({kind:'flavor',name:'Tap vanilla',price_cents:0,lead_days:0,sort_order:-2});
  const matcha=await h.product({kind:'flavor',name:'Tap matcha',price_cents:5000,lead_days:0,sort_order:-1,photos:['assets/elio-favicon.png'],builder_cutout_url:'assets/elio-apple-touch-icon.png'});
  const packaging={id:'pack',label:'Packaging?',required_count:1,choices:[
    {id:'paper',label:'Paper bag only',surcharge_cents:0},{id:'insulated',label:'Insulated bag + ice',surcharge_cents:2500}
  ]};
  const trio=await h.product({kind:'custom_box',name:'Tap to fill trio',price_cents:80000,lead_days:0,box_questions:[packaging]});
  const minimumBox=await h.product({kind:'set',box_flavors:fixed.box_flavors,name:'Two box minimum',price_cents:80000,lead_days:0,min_quantity:2,box_questions:[packaging]});
  const next=await h.day(3);
  for(const f of [vanilla,matcha])await h.inventory(f,date,12);
  await h.inventory(matcha,next,0);await h.inventory(vanilla,next,12);
  const page=await ctx.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const selectDate=async(trigger,value)=>{
    await trigger.click();
    const calendar=page.locator('#customer-calendar-popup[open]'),day=calendar.locator(`[data-customer-date="${value}"]`);
    if(!await day.count()){
      const firstVisibleDate=await calendar.locator('[data-customer-date]').first().getAttribute('data-customer-date');
      const monthStep=value<firstVisibleDate?-1:1;
      await calendar.locator(`[data-customer-month="${monthStep}"]`).click();
    }
    await day.click();
    await page.waitForFunction(d=>document.querySelector('#fulfillment-date').value===d,value);
    await page.waitForFunction(()=>!document.querySelector('#add-to-cart')?.textContent.includes('Checking'));
  };
  await page.goto(origin+'/order.html');
  await page.locator('#product-grid [data-product]').first().waitFor();
  await selectDate(page.locator('#fulfillment-date'),date);
  const dialog=page.locator('#product-dialog');
  const closeProduct=async()=>{await dialog.getByRole('button',{name:'Close product',exact:true}).click();await dialog.waitFor({state:'hidden'});};
  const openProduct=id=>page.locator(`[data-product="${id}"]`).tap();
  const insulated=dialog.getByRole('radio',{name:/Insulated bag/}),paper=dialog.getByRole('radio',{name:/Paper bag/});
  await openProduct(minimumBox.id);
  assert.equal(await dialog.locator('#add-to-cart').isDisabled(),true);
  await insulated.check();assert.equal(await dialog.locator('#detail-price').innerText(),'₱825.00');
  await paper.check();assert.equal(await dialog.locator('#detail-price').innerText(),'₱800.00');
  assert.match(await dialog.locator('.help-card').innerText(),/Minimum order: 2 boxes\./);
  await closeProduct();
  await page.locator(`[data-product="${fixed.id}"]`).click();
  assert.doesNotMatch(await dialog.locator('.help-card').innerText(),/Minimum order/);
  const fixedHeader=await dialog.locator('.modal-head').innerText();
  const fixedWidth=await dialog.evaluate(el=>el.clientWidth);
  await page.locator('#add-to-cart').click();
  await page.locator('#product-dialog').waitFor({state:'hidden'});
  const mobileBasket=page.locator('#mobile-cart'),basketLabel=mobileBasket.locator('span').first();
  assert.equal(await basketLabel.innerText(),'1 item · View basket');
  await mobileBasket.tap();
  const cart=page.locator('#quick-cart-dialog');
  await cart.getByRole('button',{name:`Increase ${fixed.name} quantity`}).tap();
  assert.equal(await basketLabel.textContent(),'2 items · View basket');
  await cart.getByRole('button',{name:`Decrease ${fixed.name} quantity`}).tap();
  assert.equal(await basketLabel.textContent(),'1 item · View basket');
  await cart.getByRole('button',{name:'Close basket'}).tap();
  await page.locator(`[data-product="${trio.id}"]`).tap();
  const tile=id=>page.locator(`[data-trio-add="${id}"]`),slot=n=>page.locator(`[data-trio-remove="${n}"]`),total=page.locator('#detail-price');
  await page.locator('#add-to-cart').waitFor();
  assert.equal(await dialog.locator('.modal-head').innerText(),fixedHeader);
  assert.equal(await dialog.evaluate(el=>el.clientWidth),fixedWidth);
  assert.equal(await dialog.locator('[data-trio-date],.ep-logo,.ep-continue').count(),0);
  assert.doesNotMatch(await dialog.locator('.help-card').innerText(),/Minimum order/);
  assert.equal(await dialog.locator('[data-trio-slots]').innerText(),'');
  const more=page.locator('[data-trio-more]');
  if(await more.isVisible())await more.tap();
  assert.match(await tile(matcha.id).innerText(),/\+₱50 each/);
  const tapRemove=async(index,dx,dy)=>{
    const cross=slot(index).locator('.ep-remove');
    await cross.scrollIntoViewIfNeeded();
    const {x,y,width,height}=await cross.boundingBox();
    await page.touchscreen.tap(x+width/2+dx,y+height/2+dy);
    await slot(index).waitFor({state:'detached',timeout:3000});
  };
  await tile(matcha.id).tap();
  await tapRemove(0,7,0);
  assert.equal(await total.innerText(),'₱800.00');
  await tile(matcha.id).tap();await tile(vanilla.id).tap();await tile(matcha.id).tap();
  const menuPhoto=await tile(matcha.id).locator('.ep-thumb img').getAttribute('src');
  assert.equal(await slot(0).locator('img.framed').getAttribute('src'),menuPhoto);
  assert.equal(await slot(2).locator('img.framed').getAttribute('src'),menuPhoto);
  assert.match(menuPhoto,/elio-favicon\.png$/);
  await slot(1).locator('.ep-fallback').waitFor({state:'visible'});
  assert.equal(await slot(1).locator('.ep-fallback').innerText(),'Tap vanilla');
  assert.equal(await total.innerText(),'₱900.00');
  assert.equal(await dialog.locator('#add-to-cart').isDisabled(),true);
  assert.match(await insulated.getAttribute('value'),/insulated/);assert.match(await insulated.locator('..').innerText(),/\+₱25\.00/);
  await insulated.check();assert.equal(await total.innerText(),'₱925.00');
  await paper.check();assert.equal(await total.innerText(),'₱900.00');
  await tapRemove(1,7,0);
  assert.equal(await slot(0).getAttribute('data-trio-flavor'),matcha.id);
  assert.equal(await slot(2).getAttribute('data-trio-flavor'),matcha.id);
  await tile(vanilla.id).tap();
  await tapRemove(0,18,0);
  assert.equal(await total.innerText(),'₱850.00');
  assert.equal(await page.locator('#add-to-cart').isDisabled(),true);
  await tile(vanilla.id).tap();
  assert.deepEqual(await page.locator('[data-trio-flavor]').evaluateAll(els=>els.map(e=>e.dataset.trioFlavor)),[vanilla.id,vanilla.id,matcha.id]);
  const changeDate=async d=>{
    await closeProduct();
    await selectDate(page.locator('#fulfillment-date'),d);
    await openProduct(trio.id);
    if(await more.isVisible())await more.tap();
  };
  await changeDate(next);
  await page.locator('#product-error').filter({hasText:'Tap matcha'}).waitFor();
  assert.equal(await slot(2).count(),0);assert.equal(await slot(1).getAttribute('data-trio-flavor'),vanilla.id);
  await changeDate(date);
  await tile(matcha.id).tap();await slot(0).tap();await tile(matcha.id).tap();
  await page.locator('#product-quantity').fill('2');assert.equal(await total.innerText(),'₱1,800.00');
  await h.inventory(matcha,date,2);
  await page.locator('#add-to-cart').tap();
  await page.locator('#product-error').filter({hasText:'Tap matcha'}).waitFor();
  assert.equal(await slot(2).count(),0);
  assert.equal(await slot(1).getAttribute('data-trio-flavor'),vanilla.id);
  assert.equal(await page.locator('#cart .cart-line').count(),1);
  await h.inventory(matcha,date,12);await changeDate(date);
  await tile(matcha.id).tap();
  assert.equal(await paper.isChecked(),true);await insulated.check();
  const add=dialog.getByRole('button',{name:/^Add to basket/});
  assert.equal(await add.count(),1);
  assert.match(await add.innerText(),/₱1,850\.00/);
  await add.evaluate(button=>{button.click();button.click();});
  await dialog.waitFor({state:'hidden'});
  assert.equal(await page.locator('#checkout-dialog').evaluate(el=>el.open),false);
  const basket=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('elio-checkout-v1')).items);
  assert.equal(basket.length,2);assert.equal(basket.find(line=>line.product_id===trio.id).quantity,2);
  assert.equal(await basketLabel.innerText(),'3 items · View basket');
  await mobileBasket.tap();
  await page.locator('#checkout-button').tap();
  const form=page.locator('#checkout-form');await form.waitFor();
  for(const [field,value] of Object.entries({buyer_name:'Trio test',buyer_email:'trio@example.test',buyer_phone:'09170000000'}))await form.locator(`[name="${field}"]`).fill(value);
  await form.locator('[name=social_platform]').selectOption('na');
  await page.locator('#review-order').tap();
  const detail=page.locator('#checkout-dialog .trio-breakdown');await detail.waitFor();
  const review=await detail.innerText();
  assert.match(review,/Trio base price\s*₱800\.00/);
  assert.match(review,/2 × Tap matcha \(\+₱50\.00 each\)\s*\+₱100\.00/);
  assert.match(review,/1 × Tap vanilla\s*Included/);
  assert.match(review,/Packaging\? — Insulated bag \+ ice\s*\+₱25\.00/);
  assert.match(review,/Box subtotal\s*₱925\.00/);
  assert.match(review,/2 boxes\s*₱1,850\.00/);
  assert.deepEqual(errors,[]);await page.close();
  console.log('PASS touch trio, repeats, hole refill, dated stock, single basket add, explicit checkout and authoritative grouped quote');
}
