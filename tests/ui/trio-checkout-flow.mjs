import assert from 'node:assert/strict';

export async function verifyTrio(ctx,h,origin,fixed,date) {
  const vanilla=await h.product({kind:'flavor',name:'Tap vanilla',price_cents:0,lead_days:0,sort_order:-2});
  const matcha=await h.product({kind:'flavor',name:'Tap matcha',price_cents:5000,lead_days:0,sort_order:-1});
  const trio=await h.product({kind:'custom_box',name:'Tap to fill trio',price_cents:80000,lead_days:0});
  const next=await h.day(3);
  for(const f of [vanilla,matcha])await h.inventory(f,date,12);
  await h.inventory(matcha,next,0);await h.inventory(vanilla,next,12);
  const page=await ctx.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const selectDate=async(trigger,value)=>{
    await trigger.click();
    const calendar=page.locator('#customer-calendar-popup[open]'),day=calendar.locator(`[data-customer-date="${value}"]`);
    if(!await day.count())await calendar.locator('[data-customer-month="1"]').click();
    await day.click();
    await page.waitForFunction(d=>document.querySelector('#fulfillment-date').value===d,value);
    await page.waitForFunction(()=>!document.querySelector('#trio-checkout')?.textContent.includes('Checking'));
  };
  await page.goto(origin+'/order.html');
  await page.locator('#product-grid [data-product]').first().waitFor();
  await selectDate(page.locator('#fulfillment-date'),date);
  await page.locator(`[data-product="${fixed.id}"]`).click();await page.locator('#add-to-cart').click();
  await page.locator('#product-dialog').waitFor({state:'hidden'});
  await page.locator(`[data-product="${trio.id}"]`).tap();
  const tile=id=>page.locator(`[data-trio-add="${id}"]`),slot=n=>page.locator(`[data-trio-remove="${n}"]`),total=page.locator('#detail-price');
  await page.locator('#trio-checkout').waitFor();
  const more=page.locator('[data-trio-more]');
  if(await more.isVisible())await more.tap();
  assert.match(await tile(matcha.id).innerText(),/\+₱50 each/);
  await tile(matcha.id).tap();await tile(vanilla.id).tap();await tile(matcha.id).tap();
  assert.equal(await total.innerText(),'₱900');
  await slot(0).tap();
  assert.equal(await total.innerText(),'₱850');
  assert.equal(await page.locator('#trio-checkout').isDisabled(),true);
  await tile(vanilla.id).tap();
  assert.deepEqual(await page.locator('[data-trio-flavor]').evaluateAll(els=>els.map(e=>e.dataset.trioFlavor)),[vanilla.id,vanilla.id,matcha.id]);
  await selectDate(page.locator('[data-trio-date]'),next);
  await page.locator('#product-error').filter({hasText:'Tap matcha'}).waitFor();
  assert.equal(await slot(2).count(),0);assert.equal(await slot(1).getAttribute('data-trio-flavor'),vanilla.id);
  await selectDate(page.locator('[data-trio-date]'),date);
  await tile(matcha.id).tap();await slot(0).tap();await tile(matcha.id).tap();
  await page.locator('#product-quantity').fill('2');assert.equal(await total.innerText(),'₱1,800');
  await h.inventory(matcha,date,2);
  await page.locator('#trio-checkout').tap();
  await page.locator('#product-error').filter({hasText:'Tap matcha'}).waitFor();
  assert.equal(await slot(2).count(),0);
  assert.equal(await slot(1).getAttribute('data-trio-flavor'),vanilla.id);
  assert.equal(await page.locator('#cart .cart-line').count(),1);
  await h.inventory(matcha,date,12);await selectDate(page.locator('[data-trio-date]'),date);
  await tile(matcha.id).tap();
  await page.locator('#trio-checkout').evaluate(button=>{button.click();button.click();});
  const form=page.locator('#checkout-form');await form.waitFor();
  const basket=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('elio-checkout-v1')).items);
  assert.equal(basket.length,2);assert.equal(basket.find(line=>line.product_id===trio.id).quantity,2);
  for(const [field,value] of Object.entries({buyer_name:'Trio test',buyer_email:'trio@example.test',buyer_phone:'09170000000'}))await form.locator(`[name="${field}"]`).fill(value);
  await form.locator('[name=social_platform]').selectOption('na');
  await page.locator('#review-order').tap();
  const detail=page.locator('#checkout-dialog .trio-breakdown');await detail.waitFor();
  const review=await detail.innerText();
  assert.match(review,/Trio base price\s*₱800\.00/);
  assert.match(review,/2 × Tap matcha \(\+₱50\.00 each\)\s*\+₱100\.00/);
  assert.match(review,/1 × Tap vanilla\s*Included/);
  assert.match(review,/Box subtotal\s*₱900\.00/);
  assert.match(review,/2 boxes\s*₱1,800\.00/);
  assert.deepEqual(errors,[]);await page.close();
  console.log('PASS touch trio, repeats, hole refill, dated stock, double checkout and authoritative grouped quote');
}
